/**
 * Hit dice and fixed bonus HP for a group at a level. Levels past the table (20) continue
 * the last row's per-level bonus.
 */
export function hitDiceAt(group, level) {
  const { die, levels } = AD2E.hitDice[group];
  const last = levels.at(-1);
  if (level <= last.level) return { die, ...levels[Math.max(level, 1) - 1] };
  const perLevel = last.bonus - levels.at(-2).bonus;
  return { die, level, dice: last.dice, bonus: last.bonus + perLevel * (level - last.level) };
}

/**
 * PHB Table 9: racial Constitution saving-throw bonus (dwarf, gnome, halfling), generated by
 * tools/build-race-data.py. Scores below the first row (4) give no bonus.
 */
AD2E.conSaveBonus = CON_SAVE_BONUS;

export function conSaveBonus(con) {
  return con < AD2E.conSaveBonus[0].min ? 0 : lookup(AD2E.conSaveBonus, con).bonus;
}

/**
 * THAC0: PHB Table 53 for levels 1-20 (generated); past level 20 the progression below continues it
 * (tools/build-level-tables.py asserts it reproduces Table 53). THAC0 = 20 - floor((level-1)/divisor)*step.
 */
AD2E.thac0Table = THAC0_TABLE;
export function thac0At(group, level) {
  const table = AD2E.thac0Table[group];
  if (level >= 1 && level <= table.length) return table[level - 1];
  const { divisor, step } = AD2E.thac0Progression[group];
  return 20 - Math.floor((Math.max(level, 1) - 1) / divisor) * step;
}

