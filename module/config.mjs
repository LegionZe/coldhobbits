/** Rate in a [{min, max, rate: [attacks, rounds]}] table for a level. */
export function attackRate(table, level) {
  return table.find(r => level >= r.min && level <= r.max)?.rate ?? [1, 1];
}

/** "3/2" for [3, 2]; "1" for [1, 1]. */
export function formatRate([attacks, rounds]) {
  return rounds === 1 ? `${attacks}` : `${attacks}/${rounds}`;
}

