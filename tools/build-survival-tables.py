#!/usr/bin/env python3
"""Generate module/rules/survival-tables.mjs: food and water on the road (module/travel-days.mjs).

Source (AD&D 2e fandom wiki, MediaWiki API): "Provisioning the Crew (CSH)" (The Complete Spacefarer's Handbook; owner's
ruling 1.0.37: these rules for starvation and thirst). Regex-checked: food a pound or so a day; days without food = half
the Constitution score, then a daily Constitution check or -1 Strength and -1 Constitution (checks with the lowered
score); Strength 0 incapacitated, Constitution 0 death unless a save vs. death magic (starvation: another day; thirst:
six more hours); starvation losses return 2 Strength and 1 Constitution a day, a score that reached 0 loses 1 point for
good unless a System Shock roll; water: 3 days without ill effects, no survival beyond a week, a Constitution check every
six hours, losses back 1 Strength and 1 Constitution an hour, no permanent loss unless also without food; "Humans require a
minimum of a gallon of water each day" (kept as data; the daily amount is the world setting `waterPerDay`, owner's ruling
1/2 gallon by default).
Run from the repo root:  python3 tools/build-survival-tables.py
"""
import importlib.util
import json
import re

_spec = importlib.util.spec_from_file_location("classdata", "tools/build-class-data.py")
classdata = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(classdata)
_tspec = importlib.util.spec_from_file_location("travel", "tools/build-travel-tables.py")
travel = importlib.util.module_from_spec(_tspec)
_tspec.loader.exec_module(travel)
need = travel.need

PAGE = "Provisioning the Crew (CSH)"
WORDS = {"one": 1, "two": 2, "three": 3, "six": 6}


def main():
    w, rev, _ = classdata.page(PAGE)
    t = re.sub(r"\s+", " ", w.replace("[[", "").replace("]]", ""))
    need(t, r"A typical human requires only a pound or so of food per day", "food per day")
    need(t, r"A character can live without food for a number of days equal to half his Constitution score without ill effects", "days without food")
    need(t, r"Thereafter, the character must make a Constitution check each day or lose one Strength point and one Constitution point", "starvation check")
    need(t, r"This Constitution check is made with each day's lowered Constitution", "lowered Constitution")
    need(t, r"When Strength reaches zero, the character is incapacitated and can no longer move", "Strength zero")
    need(t, r"When Constitution reaches zero, the character dies unless he can make a saving throw vs\. death magic\. Success indicates that the character survives for another day", "starvation death save")
    starve = need(t, r"recovered at the rate of (\w+) Strength points and (\w+) Constitution point per day", "starvation recovery")
    need(t, r"if either Strength or Constitution drops completely to zero as a result of starvation, the character loses one point of the affected attribute permanently unless he can make a System Shock roll", "permanent loss")
    free = need(t, r"No character can go without some form of water for more than (\w+) days without suffering ill effects, and under no circumstances will that character survive for more than a week", "days without water")
    every = need(t, r"After three days without water, the character must make a Constitution check every (\w+) hours or lose one Strength point and one Constitution point", "thirst check")
    need(t, r"When Constitution reaches zero, the character dies unless she can make a saving throw vs\. death magic\. Success indicates that the character lasts six more hours", "thirst death save")
    need(t, r"lost to thirst can be recovered at the rate of one Strength point and one Constitution point per hour", "thirst recovery")
    need(t, r"There is no chance of permanent characteristic loss unless the character also lacked food", "thirst permanent")
    gallon = need(t, r"Humans require a minimum of a (gallon) of water each day", "water per day")
    data = {
        "foodDivisor": 2, "waterFreeDays": WORDS[free.group(1)], "waterMaxDays": 7, "waterCheckHours": WORDS[every.group(1)],
        "starveRecover": {"str": WORDS[starve.group(1)], "con": WORDS[starve.group(2)]}, "thirstRecoverPerHour": 1,
        "deathSave": "par", "rulesWaterGallons": 1 if gallon.group(1) == "gallon" else None, "defaultWaterGallons": 0.5,
        "url": classdata.url(PAGE),
    }
    assert data["waterFreeDays"] == 3 and data["waterCheckHours"] == 6 and data["starveRecover"] == {"str": 2, "con": 1}, data
    with open("module/rules/survival-tables.mjs", "w") as f:
        f.write("// GENERATED by tools/build-survival-tables.py from the AD&D 2e fandom wiki (MediaWiki API): do not edit.\n")
        f.write(f"// Source: {PAGE} rev {rev} (starvation and thirst rules, regex-checked).\n")
        f.write(f"export const SURVIVAL_TABLES = {json.dumps(data, ensure_ascii=False)};\n")
    print(data)


if __name__ == "__main__":
    main()
